/// A physical key position, independent of layout — the thing that was actually
/// pressed. `KeyA` always means "the key in the QWERTY A position," never "the key
/// that produces the letter A" (section 4 draws this distinction explicitly). Backends
/// map their native scancode/keycode space onto this enum once, at the boundary.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[non_exhaustive]
pub enum PhysicalKey {
    KeyA, KeyB, KeyC, KeyD, KeyE, KeyF, KeyG, KeyH, KeyI, KeyJ, KeyK, KeyL, KeyM,
    KeyN, KeyO, KeyP, KeyQ, KeyR, KeyS, KeyT, KeyU, KeyV, KeyW, KeyX, KeyY, KeyZ,
    Digit0, Digit1, Digit2, Digit3, Digit4, Digit5, Digit6, Digit7, Digit8, Digit9,
    Enter, Escape, Backspace, Tab, Space,
    Minus, Equal, BracketLeft, BracketRight, Backslash, Semicolon, Quote, Grave,
    Comma, Period, Slash,
    CapsLock, ScrollLock, NumLock,
    F1, F2, F3, F4, F5, F6, F7, F8, F9, F10, F11, F12,
    PrintScreen, Pause, Insert, Home, PageUp, Delete, End, PageDown,
    ArrowRight, ArrowLeft, ArrowDown, ArrowUp,
    ControlLeft, ShiftLeft, AltLeft, SuperLeft,
    ControlRight, ShiftRight, AltRight, SuperRight,
    MediaPlayPause, MediaNextTrack, MediaPrevTrack, MediaVolumeUp, MediaVolumeDown, MediaMute,
    Compose,
    /// Escape hatch for layout-specific or vendor keys not enumerated above. Carries
    /// the backend's raw code purely for diagnostics (section 28) — never matched on
    /// by application logic.
    Other(u32),
}

/// The character/action a physical key produces *after* layout mapping — what an
/// application-level shortcut binding should compare against. Multiple physical keys
/// can map to the same logical key on some layouts, and the same physical key can map
/// to different logical keys across layouts.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[non_exhaustive]
pub enum LogicalKey {
    Character(char),
    Enter,
    Escape,
    Backspace,
    Tab,
    Space,
    CapsLock,
    ScrollLock,
    NumLock,
    Function(u8),
    PrintScreen,
    Pause,
    Insert,
    Home,
    PageUp,
    Delete,
    End,
    PageDown,
    ArrowRight,
    ArrowLeft,
    ArrowDown,
    ArrowUp,
    Control,
    Shift,
    Alt,
    Super,
    MediaPlayPause,
    MediaNextTrack,
    MediaPrevTrack,
    MediaVolumeUp,
    MediaVolumeDown,
    MediaMute,
    Compose,
    Unidentified,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum KeyAction {
    Down,
    Up,
    /// Auto-repeat while held, generated by [`KeyboardState`] — not by the backend —
    /// so repeat timing is one place, not re-derived per platform (section 4).
    Repeat,
}

/// Ctrl / Alt / Shift / Super plus the three lock keys, tracked as live state rather
/// than re-derived per event, so every [`InputEvent`](crate::event::InputEvent) can
/// carry an authoritative modifier snapshot (section 4, section 11).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
pub struct Modifiers {
    pub ctrl: bool,
    pub alt: bool,
    pub shift: bool,
    pub logo: bool,
    pub caps_lock: bool,
    pub num_lock: bool,
    pub scroll_lock: bool,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct KeyboardEvent {
    pub physical_key: PhysicalKey,
    pub logical_key: LogicalKey,
    /// Text an input-method/layout would insert, if any — punctuation and letter keys
    /// carry it, `ArrowLeft` or a bare modifier does not. Kept separate from
    /// `logical_key` so shortcut handling never has to parse text back into a key
    /// (section 4's physical → logical → text pipeline, stopping short of full IME
    /// composition which section 4 leaves to the application layer).
    pub text: Option<String>,
    pub action: KeyAction,
}

/// Maps [`PhysicalKey`] to [`LogicalKey`]/text. `UsQwerty` is the only implementation
/// today; international layouts and compose-key sequences (section 4) plug in here
/// without touching event plumbing.
pub trait KeyboardLayout: Send + Sync {
    fn name(&self) -> &str;
    fn map(&self, key: PhysicalKey, modifiers: Modifiers) -> LogicalKey;
    fn text_for(&self, logical: LogicalKey, modifiers: Modifiers) -> Option<String>;
}

pub struct UsQwertyLayout;

