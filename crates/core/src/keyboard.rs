fn char_key(lower: char, upper: char, shifted: bool) -> LogicalKey {
    LogicalKey::Character(if shifted { upper } else { lower })
}

/// Live per-keyboard state: which physical keys are held, and the derived modifier
/// snapshot every event on that device carries. One instance per keyboard device so
/// unplugging one keyboard mid-chord can't leave another keyboard's modifiers stuck
/// (section 9's "existing focus/grab state cleaned up" on device removal).
#[derive(Debug, Default)]
pub struct KeyboardState {
    pressed: HashSet<PhysicalKey>,
    modifiers: Modifiers,
}

impl KeyboardState {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn modifiers(&self) -> Modifiers {
        self.modifiers
    }

    pub fn is_pressed(&self, key: PhysicalKey) -> bool {
        self.pressed.contains(&key)
    }

    pub fn pressed_keys(&self) -> impl Iterator<Item = &PhysicalKey> {
        self.pressed.iter()
    }

    /// Returns `true` the first time a key transitions down (repeats produced by an
    /// already-held key are the backend's/compositor's concern, not double-counted
    /// here).
    pub fn note_down(&mut self, key: PhysicalKey) -> bool {
        self.update_modifier(key, true);
        self.pressed.insert(key)
    }

    pub fn note_up(&mut self, key: PhysicalKey) -> bool {
        self.update_modifier(key, false);
        self.pressed.remove(&key)
    }

    fn update_modifier(&mut self, key: PhysicalKey, is_down: bool) {
        match key {
            PhysicalKey::ControlLeft | PhysicalKey::ControlRight => self.modifiers.ctrl = is_down,
            PhysicalKey::AltLeft | PhysicalKey::AltRight => self.modifiers.alt = is_down,
            PhysicalKey::ShiftLeft | PhysicalKey::ShiftRight => self.modifiers.shift = is_down,
            PhysicalKey::SuperLeft | PhysicalKey::SuperRight => self.modifiers.logo = is_down,
            PhysicalKey::CapsLock if is_down => self.modifiers.caps_lock = !self.modifiers.caps_lock,
            PhysicalKey::NumLock if is_down => self.modifiers.num_lock = !self.modifiers.num_lock,
            PhysicalKey::ScrollLock if is_down => self.modifiers.scroll_lock = !self.modifiers.scroll_lock,
            _ => {}
        }
    }
}

/// Registry of per-device keyboard state, owned by
/// [`InputService`](crate::service::InputService).
#[derive(Debug, Default)]
pub struct KeyboardStateTable(std::collections::HashMap<InputDeviceId, KeyboardState>);

impl KeyboardStateTable {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn state_mut(&mut self, device: InputDeviceId) -> &mut KeyboardState {
        self.0.entry(device).or_default()
    }

    pub fn remove(&mut self, device: InputDeviceId) {
        self.0.remove(&device);
    }

    /// Modifier state isn't scoped to "the keyboard that produced this event" in a
    /// single-seat desktop — Ctrl held on one keyboard and a click on the mouse should
    /// still register as a Ctrl-click. [`InputService`](crate::service::InputService)
    /// ORs every connected keyboard's modifiers together for non-keyboard events.
    pub fn aggregate(&self) -> Modifiers {
        self.0.values().fold(Modifiers::default(), |mut acc, state| {
            let m = state.modifiers();
            acc.ctrl |= m.ctrl;
            acc.alt |= m.alt;
            acc.shift |= m.shift;
            acc.logo |= m.logo;
            acc.caps_lock |= m.caps_lock;
            acc.num_lock |= m.num_lock;
            acc.scroll_lock |= m.scroll_lock;
            acc
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn holding_ctrl_sets_modifier_and_releasing_clears_it() {
        let mut state = KeyboardState::new();
        assert!(!state.modifiers().ctrl);

        state.note_down(PhysicalKey::ControlLeft);
        assert!(state.modifiers().ctrl);

        state.note_up(PhysicalKey::ControlLeft);
        assert!(!state.modifiers().ctrl);
    }

    #[test]
    fn caps_lock_toggles_rather_than_tracks_held_state() {
        let mut state = KeyboardState::new();
        state.note_down(PhysicalKey::CapsLock);
        assert!(state.modifiers().caps_lock);
        state.note_up(PhysicalKey::CapsLock);
        // Releasing the key must not itself flip caps lock back off.
        assert!(state.modifiers().caps_lock);
        state.note_down(PhysicalKey::CapsLock);
        assert!(!state.modifiers().caps_lock);
    }

    #[test]
    fn note_down_reports_first_transition_only() {
        let mut state = KeyboardState::new();
        assert!(state.note_down(PhysicalKey::KeyA));
        assert!(!state.note_down(PhysicalKey::KeyA));
    }

    #[test]
    fn us_qwerty_distinguishes_physical_logical_and_text() {
        let layout = UsQwertyLayout;
        let logical = layout.map(PhysicalKey::KeyA, Modifiers::default());
        assert_eq!(logical, LogicalKey::Character('a'));
        assert_eq!(layout.text_for(logical, Modifiers::default()), Some("a".to_string()));

        let shifted = Modifiers { shift: true, ..Default::default() };
        assert_eq!(layout.map(PhysicalKey::KeyA, shifted), LogicalKey::Character('A'));

        // A non-character physical key must not fabricate text.
        let arrow = layout.map(PhysicalKey::ArrowLeft, Modifiers::default());
        assert_eq!(arrow, LogicalKey::ArrowLeft);
        assert_eq!(layout.text_for(arrow, Modifiers::default()), None);
    }

    #[test]
    fn aggregate_ors_modifiers_across_keyboards() {
        let mut table = KeyboardStateTable::new();
        let kb1 = InputDeviceId::new();
        let kb2 = InputDeviceId::new();
        table.state_mut(kb1).note_down(PhysicalKey::ControlLeft);
        table.state_mut(kb2).note_down(PhysicalKey::ShiftLeft);

        let aggregated = table.aggregate();
        assert!(aggregated.ctrl);
        assert!(aggregated.shift);
        assert!(!aggregated.alt);
    }

    #[test]
    fn removing_a_device_drops_its_state() {
        let mut table = KeyboardStateTable::new();
        let kb = InputDeviceId::new();
        table.state_mut(kb).note_down(PhysicalKey::ControlLeft);
        assert!(table.aggregate().ctrl);

        table.remove(kb);
        assert!(!table.aggregate().ctrl);
    }
}
